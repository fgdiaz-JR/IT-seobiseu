CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(40) NOT NULL,
    descripcion VARCHAR2(200),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id NUMBER NOT NULL,
    nombre VARCHAR2(120) NOT NULL,
    correo VARCHAR2(160) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    activo CHAR(1) DEFAULT 'S' NOT NULL,
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE clientes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR2(180) NOT NULL,
    identificacion_fiscal VARCHAR2(30) NOT NULL,
    correo_contacto VARCHAR2(160),
    telefono VARCHAR2(30),
    estado VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sedes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id NUMBER NOT NULL,
    nombre VARCHAR2(120) NOT NULL,
    direccion VARCHAR2(250) NOT NULL,
    contacto VARCHAR2(120),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sla (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(80) NOT NULL,
    prioridad VARCHAR2(10) NOT NULL,
    horas_respuesta NUMBER(5,2) NOT NULL,
    horas_resolucion NUMBER(5,2) NOT NULL,
    activo CHAR(1) DEFAULT 'S' NOT NULL
);

CREATE TABLE tickets (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id NUMBER NOT NULL,
    sede_id NUMBER,
    creado_por NUMBER NOT NULL,
    asignado_a NUMBER,
    sla_id NUMBER,
    tipo_requerimiento VARCHAR2(50) NOT NULL,
    prioridad VARCHAR2(10) NOT NULL,
    estado VARCHAR2(25) DEFAULT 'ABIERTO' NOT NULL,
    asunto VARCHAR2(180) NOT NULL,
    descripcion VARCHAR2(2000) NOT NULL,
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    cerrado_en TIMESTAMP
);

CREATE TABLE ordenes_trabajo (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id NUMBER,
    cliente_id NUMBER NOT NULL,
    tecnico_id NUMBER,
    equipo VARCHAR2(160),
    serial_equipo VARCHAR2(100),
    prioridad VARCHAR2(10) NOT NULL,
    estado VARCHAR2(25) DEFAULT 'PENDIENTE' NOT NULL,
    diagnostico VARCHAR2(2000),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE inventario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR2(60) NOT NULL,
    nombre VARCHAR2(180) NOT NULL,
    categoria VARCHAR2(80) NOT NULL,
    stock NUMBER(10) DEFAULT 0 NOT NULL,
    stock_minimo NUMBER(10) DEFAULT 0 NOT NULL,
    precio_unitario NUMBER(12,2) DEFAULT 0 NOT NULL,
    ubicacion VARCHAR2(100),
    activo CHAR(1) DEFAULT 'S' NOT NULL,
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE movimientos_inventario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventario_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    tipo VARCHAR2(15) NOT NULL,
    cantidad NUMBER(10) NOT NULL,
    motivo VARCHAR2(250) NOT NULL,
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE bitacora_tickets (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    comentario VARCHAR2(2000) NOT NULL,
    estado_nuevo VARCHAR2(25),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
